CREATE TABLE IF NOT EXISTS stations (
    site_id VARCHAR(50) NOT NULL,
    technology VARCHAR(50) NOT NULL DEFAULT '',
    end_id VARCHAR(50) NOT NULL DEFAULT '',
    contract_area_type VARCHAR(100) NOT NULL DEFAULT '',
    area_holder VARCHAR(150) NOT NULL DEFAULT '',
    infrastructure_type VARCHAR(100) NOT NULL DEFAULT '',
    ev_type VARCHAR(100) NOT NULL DEFAULT '',
    address VARCHAR(255) NOT NULL DEFAULT '',
    neighborhood VARCHAR(150) NOT NULL DEFAULT '',
    city VARCHAR(150) NOT NULL DEFAULT '',
    state CHAR(2) NOT NULL DEFAULT '',
    zip_code VARCHAR(20) NOT NULL DEFAULT '',
    regional VARCHAR(100) NOT NULL DEFAULT '',
    latitude DECIMAL(10, 6) NULL,
    longitude DECIMAL(10, 6) NULL,
    status VARCHAR(50) NOT NULL DEFAULT '',
    tower_type VARCHAR(100) NOT NULL DEFAULT '',
    nominal_aev VARCHAR(100) NOT NULL DEFAULT '',
    station_id VARCHAR(100) NOT NULL DEFAULT '',
    ev_supplier VARCHAR(150) NOT NULL DEFAULT '',
    land_area DECIMAL(12, 2) NULL,
    structure_height DECIMAL(10, 2) NULL,
    observation TEXT NOT NULL,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (site_id),
    KEY idx_stations_city (city),
    KEY idx_stations_state (state),
    KEY idx_stations_status (status),
    KEY idx_stations_station_id (station_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
